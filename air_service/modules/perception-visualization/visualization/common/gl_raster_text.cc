GLuint GLRasterText::s_font_offset_ = 0;

void GLRasterText::MakeRasterFont() {
  GLuint i;
  GLuint j;
  glPixelStorei(GL_UNPACK_ALIGNMENT, 1);

  s_font_offset_ = glGenLists(128);

  for (i = 0, j = ' '; i < 95; ++i, ++j) {
    glNewList(s_font_offset_ + j, GL_COMPILE);
    glBitmap(8, 13, 0.0, 2.0, 10.0, 0.0, s_asccii_bitmaps_[i]);
    glEndList();
  }
}

void GLRasterText::Init() {
  glShadeModel(GL_FLAT);
  MakeRasterFont();
}

void GLRasterText::DrawString(
    const char *s, int x, int y, int r, int g, int b) {
  glColor3ub(r, g, b);

  glRasterPos2i(x, y);

  glPushAttrib(GL_LIST_BIT);
  glListBase(s_font_offset_);
  glCallLists(
      strlen(s), GL_UNSIGNED_BYTE,
      reinterpret_cast<GLubyte *>(const_cast<char *>(s)));
  glPopAttrib();

  glColor4f(1, 1, 1, 1);  // reset the color to white
}

void GLRasterText::PrintString(const char *s) {
  glPushAttrib(GL_LIST_BIT);
  glListBase(s_font_offset_);
  glCallLists(
      strlen(s), GL_UNSIGNED_BYTE,
      reinterpret_cast<GLubyte *>(const_cast<char *>(s)));
  glPopAttrib();
}

